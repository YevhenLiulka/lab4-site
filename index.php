<?php
$group = "Група - CH 41"; 
$pib = "Люлька Євген Валентинович"; 
$creationDate = "21.09.2026"; // Дата створення документу
$currentDate = date("d.m.Y H:i:s"); // Поточна дата, генерується автоматично

echo "<h2>Лабораторна робота: Оператор switch-case</h2>";
echo "<p><b>Розробник:</b> $pib, $group</p>";
echo "<p><b>Дата створення:</b> $creationDate</p>";
echo "<p><b>Поточна дата:</b> $currentDate</p>";
echo "<hr>";

// ==========================================
// 2. ЗМІННА ДЛЯ ПЕРЕВІРКИ
// ==========================================
// Задаємо номер кольору веселки (від 1 до 7)
// Змінюй це число, щоб перевірити різні варіанти
$color_number = 3; 

echo "<h3>Номер кольору для перевірки: $color_number</h3>";

// ==========================================
// 3. КЛАСИЧНИЙ СИНТАКСИС SWITCH
// ==========================================
echo "<h4>Результат (Класичний switch):</h4>";

switch ($color_number) {
    case 1: // Червоний
    case 2: // Помаранчевий
    case 3: // Жовтий
        echo "<p style='color: orange;'>Це теплий колір.</p>";
        break; // Зупиняємо виконання, якщо знайшли збіг
        
    case 4: // Зелений
    case 5: // Блакитний
    case 6: // Синій
    case 7: // Фіолетовий
        echo "<p style='color: blue;'>Це холодний колір.</p>";
        break;
        
    default: // Якщо ввели число не від 1 до 7
        echo "<p style='color: red;'>Помилка: введіть число від 1 до 7.</p>";
        break;
}

// ==========================================
// 4. АЛЬТЕРНАТИВНИЙ СИНТАКСИС SWITCH
// ==========================================
echo "<h4>Результат (Альтернативний switch):</h4>";

switch ($color_number):
    case 1:
    case 2:
    case 3:
        echo "<p style='color: orange;'>Це теплий колір.</p>";
        break;
        
    case 4:
    case 5:
    case 6:
    case 7:
        echo "<p style='color: blue;'>Це холодний колір.</p>";
        break;
        
    default:
        echo "<p style='color: red;'>Помилка: введіть число від 1 до 7.</p>";
        break; // Тут break не обов'язковий, але є хорошим тоном
endswitch;
?>